#!/usr/bin/env node
/**
 * СВЕРКА WASM ↔ NATIVE (F0-8) и разбор падающих профилей (F0-27).
 *
 * ЗАЧЕМ. Вердикт «WASM-сборка считает правильно» до сих пор не вынесен: мы
 * знаем только, что она считает ПОХОЖЕ на саму себя. Пока native не подтвердил
 * числа, браузерный лейн публиковать нельзя — мы показывали бы людям цифры, не
 * зная, верны ли они. Доверие к числам это единственное, что мы продаём.
 *
 * ЧТО ДЕЛАЕТ. Гоняет тот же набор профилей с теми же параметрами (набор и сам
 * прогонщик импортируются из canary.mjs — второго списка и второй реализации
 * нет по построению) ДВАЖДЫ: в браузерной сборке и в нативном контейнере, — и
 * сравнивает эти два живых прогона между собой.
 *
 * ⚠️ ИМЕННО ДВА ЖИВЫХ ПРОГОНА, А НЕ ПРОГОН ПРОТИВ БАЗОВОЙ ЛИНИИ. До 2026-08-11
 * скрипт брал числа WASM из `canary-baseline.json`, и это было незаметно
 * ошибочно: пока закреплённая сборка совпадает с той, на которой снята линия,
 * ответ случайно верен. На первом же патче он объявил дрейф баланса «багом
 * сборки». Подробности — у `прогнатьWasm`.
 *
 * ПОРОГ 0,5% — из docs/02 §4. Расхождение выше — это баг сборки, а не баланс:
 * seed, число итераций и target_error одинаковы, значит различаться числа могут
 * только из-за самой сборки.
 *
 * ⚠️ ЧЕТЫРЕ ПРОФИЛЯ РОНЯЮТ WASM (Blood DK, Mage Frost, Priest Shadow, Evoker
 * Devastation). Главный вопрос этого прогона — падает ли на них native:
 *  · падает тоже  → баг апстрима, ждём и сообщаем им;
 *  · не падает    → баг НАШЕЙ WASM-сборки, чинить нам, лейн держим закрытым.
 *
 * Запуск:  node scripts/compare-native.mjs
 */

import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
// ⚠️ ITERATIONS и TARGET_ERROR намеренно НЕ импортируются: у сверки свои
// параметры (см. ИТЕРАЦИЙ_СВЕРКИ ниже). Набор и прогонщик — общие с линией,
// второй реализации нет по построению.
import { наборПрофиля, PROFILES, runProfile, SEED } from './canary.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
// Базовая линия здесь БОЛЬШЕ НЕ ЧИТАЕТСЯ намеренно: сверка меряет две живые
// сборки, а не сравнивает одну из них с прошлым (см. `прогнатьWasm` ниже).
/**
 * Итог сверки в машинном виде.
 *
 * ⚠️ ЗАЧЕМ ФАЙЛ, А НЕ ТОЛЬКО ПЕЧАТЬ. Максимальное расхождение с нативом — это
 * число, которое сайт показывает людям («12/12 в пределах 0,21%»). Пока оно
 * жило только в выводе на экран, его переносили в код руками, а руками
 * переносимое число рано или поздно отстаёт от истины. Теперь его забирает
 * `pnpm sync:canaries` в основном репозитории.
 */
const ИТОГ_ФАЙЛ = resolve(HERE, '..', 'native-compare.json');
const ОБРАЗ = process.env.ENGINE_IMAGE ?? 'burstsim-engine:native';

/**
 * ⚠️ У СВЕРКИ СВОИ ПАРАМЕТРЫ, И ЭТО НЕ ДУБЛИРОВАНИЕ (заведено 2026-08-11).
 *
 * Базовая линия и сверка отвечают на РАЗНЫЕ вопросы:
 *  · линия — «сколько DPS», ей нужна статистически сошедшаяся оценка, и
 *    `target_error` там уместен;
 *  · сверка — «одинаково ли считают две сборки», это проверка эквивалентности,
 *    и ей нужна ВОСПРОИЗВОДИМОСТЬ.
 *
 * `target_error` останавливает прогон, когда погрешность падает до заданной.
 * Два независимых прогона останавливаются на разном числе итераций — и разница
 * между ними становится случайной величиной ТОГО ЖЕ ПОРЯДКА, что и порог.
 * Замер 2026-08-11: три сверки одной и той же пары сборок дали по Druid Balance
 * 0,095% / −0,53% / +0,13%. Во втором прогоне профиль формально «расходился»,
 * в третьем сходился; сборка между прогонами не менялась. Проверка мерила шум.
 *
 * Поэтому здесь `target_error` выключен, а число итераций фиксировано: при
 * одинаковом seed обе сборки делают одинаковую работу, и любое расхождение
 * становится свойством сборки, а не случая. Цена — прогон всегда полный,
 * ранней остановки нет.
 */
const ИТЕРАЦИЙ_СВЕРКИ = Number(process.env.COMPARE_ITERATIONS ?? 2000);
const TARGET_ERROR_СВЕРКИ = 0; // выключен намеренно, см. выше

/**
 * ПОРОГ ВЫВЕДЕН ИЗ ИЗМЕРЕНИЯ (2026-08-11), а не назначен на глаз.
 *
 * ЗАМЕР. Две сверки подряд на ОДНИХ И ТЕХ ЖЕ сборках, параметры одинаковы:
 *  · расхождение WASM ↔ native   — до 0,30%;
 *  · разброс между прогонами     — до 0,28%  ← пол измерения;
 *  · WASM САМ С СОБОЙ            — до 0,154% ← сборка невоспроизводима.
 *
 * ⚠️ ИСТИННОГО НУЛЯ ЗДЕСЬ НЕ БЫВАЕТ. Выключение `target_error` сжало шум с
 * 0,49% до 0,30%, но не убрало: при `threads=8` итерации распределяются между
 * потоками не детерминированно, и один и тот же движок на одном и том же seed
 * даёт слегка разные числа. Полная воспроизводимость потребовала бы
 * `threads=1` — это кратно дольше и на патч-день не укладывается.
 *
 * ОТСЮДА ПОРОГ. Прежние 0,5% стояли всего в 1,8 раза выше пола — и мы это
 * наблюдали живьём: −0,53% у Druid Balance при полностью исправных сборках.
 * Гейт, срабатывающий на выпадение монетки, перестают читать. 1,0% — это
 * примерно 3,5 пола: ложных тревог не даёт, а всё настоящее ловит, потому что
 * реальные поломки сборки у нас проявлялись не полупроцентом, а падением
 * профиля целиком (см. журнал тупиков, `-fwasm-exceptions`).
 *
 * ⚠️ НЕ ПУТАТЬ ПОРОГ С ИЗМЕРЕННЫМ. Сайту показывается фактическое расхождение
 * (0,30%), а не порог. Порог — это когда бить тревогу, а не что мы намерили.
 */
const ПОРОГ = Number(process.env.COMPARE_THRESHOLD ?? 1.0);

/**
 * Профили лежат внутри образа: /profiles — часть апстрима, а не обвязки.
 *
 * ⚠️ Отчёт пишется в ФАЙЛ внутри контейнера, а наружу отдаётся только он.
 * Через `json2=/dev/stdout` движок смешивает JSON с текстовым отчётом в одном
 * потоке, и разбор ломается на первом же прогоне. Заодно так виден код выхода
 * самого движка, а не последней команды конвейера.
 */
function прогнать(name) {
  const команда =
    `simc /profiles/${наборПрофиля(name)}/${name}.simc ` +
    `iterations=${ИТЕРАЦИЙ_СВЕРКИ} target_error=${TARGET_ERROR_СВЕРКИ} seed=${SEED} threads=8 ` +
    `json2=/tmp/o.json html= report_details=0 >/tmp/log 2>&1 || { tail -3 /tmp/log >&2; exit 42; }; ` +
    `cat /tmp/o.json`;

  const итог = spawnSync(
    'docker',
    ['run', '--rm', '--network=none', '--entrypoint', '/bin/sh', ОБРАЗ, '-c', команда],
    { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
  );

  if (итог.error) return { name, error: `docker не запустился: ${итог.error.message}` };
  if (итог.status !== 0) {
    const хвост = (итог.stderr ?? '').trim().split('\n').slice(-2).join(' | ');
    return { name, error: `движок завершился с кодом ${итог.status}${хвост ? ': ' + хвост : ''}` };
  }

  try {
    const отчёт = JSON.parse(итог.stdout ?? '');
    const игрок = отчёт?.sim?.players?.[0];
    const dps = игрок?.collected_data?.dps?.mean;
    if (typeof dps !== 'number') return { name, error: 'в отчёте нет DPS' };
    return { name, dps };
  } catch (е) {
    return { name, error: `отчёт не разобрался: ${е.message}` };
  }
}

/**
 * ⚠️ ЧИСЛА WASM БЕРУТСЯ ЖИВЫМ ПРОГОНОМ, А НЕ ИЗ БАЗОВОЙ ЛИНИИ (починено
 * 2026-08-11, учения F0-17).
 *
 * ЧТО БЫЛО. Скрипт читал `canary-baseline.json` и сравнивал native С НИМ. Пока
 * закреплённая сборка совпадает с той, на которой снята линия, эти числа
 * равны — и ответ случайно верен. Ошибка проявляется ТОЛЬКО при смене сборки,
 * то есть ровно в патч-день, ровно когда сверка и нужна.
 *
 * ЧЕМ КОНЧИЛОСЬ. На патче 12.1 скрипт объявил «расхождений 8 — это баг
 * сборки», хотя мерил дрейф баланса, и записал в `native-compare.json`
 * `converged: 0, max_delta_pct: 0`. Файл читает `pnpm sync:canaries` — сайт
 * заявил бы людям, что с нативом не сошёлся ни один профиль. Настоящее
 * расхождение при пересчёте вручную: максимум 0,302% при пороге 0,5%.
 *
 * УРОК. Сверка обязана мерить ОБЕ стороны в одном прогоне. Величина, взятая
 * из файла, — это прошлое, а не измерение.
 */
async function прогнатьWasm() {
  const карта = new Map();
  for (const [i, name] of PROFILES.entries()) {
    process.stdout.write(`  WASM [${i + 1}/${PROFILES.length}] ${name} … `);
    const r = await runProfile(name, { iterations: ИТЕРАЦИЙ_СВЕРКИ, targetError: TARGET_ERROR_СВЕРКИ });
    console.log(r.error ? `ОШИБКА: ${String(r.error).slice(0, 80)}` : `${Math.round(r.dps)} DPS`);
    карта.set(name, r);
  }
  return карта;
}

console.log('\nПрогон WASM (числа для сверки берутся здесь, а не из базовой линии)');
console.log('─'.repeat(78));
const wasm = await прогнатьWasm();

console.log('\nСВЕРКА WASM ↔ NATIVE');
console.log(
  `образ ${ОБРАЗ} · seed ${SEED} · iterations ${ИТЕРАЦИЙ_СВЕРКИ} · target_error выключен · порог ${ПОРОГ}%`,
);
console.log('(параметры сверки СВОИ, не линии: здесь нужна воспроизводимость, а не оценка)');
console.log('─'.repeat(78));

const строки = [];
for (const [i, name] of PROFILES.entries()) {
  process.stdout.write(`[${i + 1}/${PROFILES.length}] ${name} … `);
  const н = прогнать(name);
  const в = wasm.get(name);
  const wasmDps = typeof в?.dps === 'number' ? в.dps : null;
  const wasmУпал = Boolean(в?.error) || wasmDps === null;

  if (н.error) {
    console.log(`native: ОШИБКА — ${н.error}`);
    строки.push({ name, вердикт: wasmУпал ? 'падают оба' : 'падает только native', детали: н.error });
    continue;
  }

  console.log(`${Math.round(н.dps)} DPS`);
  if (wasmУпал) {
    строки.push({ name, вердикт: 'падает только WASM', native: н.dps });
    continue;
  }
  const дельта = ((н.dps - wasmDps) / wasmDps) * 100;
  строки.push({
    name,
    вердикт: Math.abs(дельта) <= ПОРОГ ? 'сходится' : 'РАСХОЖДЕНИЕ',
    wasm: wasmDps,
    native: н.dps,
    дельта,
  });
}

console.log('\n' + '─'.repeat(78));
for (const с of строки) {
  const числа =
    с.дельта === undefined
      ? (с.native ? `native ${Math.round(с.native)}` : с.детали ?? '')
      : `${Math.round(с.wasm)} → ${Math.round(с.native)}  ${с.дельта >= 0 ? '+' : ''}${с.дельта.toFixed(2)}%`;
  console.log(`  ${с.name.padEnd(30)} ${с.вердикт.padEnd(22)} ${числа}`);
}

const расхождения = строки.filter((с) => с.вердикт === 'РАСХОЖДЕНИЕ');
const толькоWasm = строки.filter((с) => с.вердикт === 'падает только WASM');
const толькоNative = строки.filter((с) => с.вердикт === 'падает только native');
const обаПадают = строки.filter((с) => с.вердикт === 'падают оба');

console.log('\nИТОГ');
console.log(`  сошлось в пределах ${ПОРОГ}%: ${строки.filter((с) => с.вердикт === 'сходится').length}`);
if (расхождения.length) console.log(`  ❌ расхождений: ${расхождения.length} — это баг сборки, а не баланс`);
if (обаПадают.length) console.log(`  падают обе сборки: ${обаПадают.length} → баг апстрима, наша вина исключена`);
if (толькоWasm.length) console.log(`  ❌ падает только WASM: ${толькоWasm.length} → баг НАШЕЙ сборки, лейн держим закрытым`);
if (толькоNative.length) console.log(`  ⚠️ падает только native: ${толькоNative.length} → разбирать отдельно`);

const сошлись = строки.filter((с) => с.вердикт === 'сходится');
const максДельта = сошлись.reduce((m, с) => Math.max(m, Math.abs(с.дельта ?? 0)), 0);

// Первый профиль, который реально посчитался: у него и спрашиваем версии.
const живой = [...wasm.values()].find((r) => r && !r.error && typeof r.dps === 'number');

writeFileSync(
  ИТОГ_ФАЙЛ,
  JSON.stringify(
    {
      _: 'Итог сверки WASM ↔ native. Пишется compare-native.mjs, читается pnpm sync:canaries в основном репозитории. Руками не править.',
      compared: new Date().toISOString().slice(0, 10),
      threshold_pct: ПОРОГ,
      converged: сошлись.length,
      total: строки.length,
      max_delta_pct: Number(максДельта.toFixed(2)),
      // ⚠️ ВЕРСИИ БЕРУТСЯ ИЗ ЖИВОГО ПРОГОНА, А НЕ ИЗ БАЗОВОЙ ЛИНИИ. Раньше
      // здесь читалась линия — то есть файл заявлял версию ПРОШЛОЙ сборки,
      // даже когда мерили новую. На патче 12.1 это дало бы `12.0.7.68887` при
      // фактических `12.1.0.69214`, и сайт показал бы людям чужой билд.
      build: живой?.build ?? null,
      wow_version: живой?.wow_build?.wow_version ?? живой?.wow_build ?? null,
    },
    null,
    2,
  ) + '\n',
);
console.log(`  итог записан: ${ИТОГ_ФАЙЛ} (максимум ${максДельта.toFixed(2)}%)`);

console.log('');
process.exit(расхождения.length || толькоWasm.length || толькоNative.length ? 1 : 0);
